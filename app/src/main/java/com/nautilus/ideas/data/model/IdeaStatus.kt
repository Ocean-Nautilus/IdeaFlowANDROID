package com.nautilus.ideas.data.model

/**
 * Стадия, на которой находится идея.
 *
 * Хранится в базе строкой (см. [com.nautilus.ideas.data.db.Converters]),
 * а не числом: если позже добавится новый статус, порядок элементов
 * перестанет иметь значение и старые записи не "переедут" на чужой статус.
 */
enum class IdeaStatus {
    /** Только что записана, к работе не приступали. */
    NEW,

    /** Идею начали воплощать. */
    IN_PROGRESS,

    /** Идея реализована. */
    DONE,

    /** Отложена на потом. */
    POSTPONED
}
